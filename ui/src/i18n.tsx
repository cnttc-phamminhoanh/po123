export type TKey = keyof typeof translations['en'];
export type Dict = Record<TKey, string>;

const dicts: Record<Locale, Dict> = translations;

interface I18nValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export const I18nProvider = ({ children }: { children: ReactNode }) => {
  const [locale, setLocale] = useState<Locale>(() => {
    if (typeof window === 'undefined') return 'en';
    const saved: string | null = window.localStorage.getItem(STORAGE_KEY);
    return saved === 'vi' || saved === 'en' || saved === 'zh' ? saved : 'en';
  });

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, locale);
  }, [locale]);

  const t = (key: TKey, vars?: Record<string, string | number>): string => {
    let text: string = dicts[locale][key] ?? dicts.en[key] ?? key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        text = text.split(`{${name}}`).join(String(value));
      }
    }
    return text;
  };

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
};

export const useI18n = (): I18nValue => {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used within I18nProvider');
  return value;
};

export const useT = (): I18nValue['t'] => useI18n().t;

export const LanguageSwitcher = () => {
  const { locale, setLocale } = useI18n();
  return (
    <Select
      value={locale}
      onValueChange={(value) => setLocale(value as Locale)}
    >
      <SelectTrigger className="lang-select" aria-label="Language">
        <SelectValue />
      </SelectTrigger>
      <SelectContent className="rounded-[8px]">
        <SelectItem value="en">English</SelectItem>
        <SelectItem value="vi">Tiếng Việt</SelectItem>
        <SelectItem value="zh">中文</SelectItem>
      </SelectContent>
    </Select>
  );
};
