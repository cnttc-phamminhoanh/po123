const splitGroups = (prefix, from, to, total) => {
  const names = [];
  for (let index = from; index <= to; index += 1) names.push(`${prefix}-${index}`);
  const base = Math.floor(total / names.length);
  let assigned = 0;
  return names.map((sizeGroup, index) => {
    const isLast = index === names.length - 1;
    const qty = isLast ? total - assigned : base;
    assigned += qty;
    return { sizeGroup, qty, shippedQty: Math.round(qty * 0.97) };
  });
};

